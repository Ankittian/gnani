"use client";

import { useRef } from "react";
import { useRouter } from "next/navigation";
import { motion } from "motion/react";
import { useTranslations } from "next-intl";
import { FileAudio, Mic, Square, X } from "@/components/common/icons";
import { BottomSheet } from "@/components/common/BottomSheet";
import { press } from "@/components/common/motion";
import { DostOrb } from "@/components/orb/DostOrb";
import { useLongTranscribe } from "@/hooks/useLongTranscribe";
import { useRecorder } from "@/hooks/useRecorder";
import { LANGUAGES } from "@/lib/i18n/languages";
import type { MessageKey } from "@/lib/i18n/messages";
import type { Shop } from "@/lib/types";

/** Synthetic noisy customer voice orders generated by scripts/make_fixtures.py (Timbre + mixed shop noise). */
export const SAMPLE_ORDERS: { file: string; lang: keyof typeof LANGUAGES | null; note: MessageKey | null; flag: string }[] = [
  { file: "/fixtures/samples/order-hi-noisy.wav", lang: "hi-IN", note: "sampleNoisy", flag: "🔊" },
  { file: "/fixtures/samples/order-kn-noisy.wav", lang: "kn-IN", note: "sampleNoisy", flag: "🔊" },
  { file: "/fixtures/samples/order-ta.wav", lang: "ta-IN", note: null, flag: "🎧" },
  { file: "/fixtures/samples/order-hinglish-long.wav", lang: null, note: "sampleLong", flag: "⏱️" },
];

const STAGE_KEY: Record<string, MessageKey> = {
  decoding: "stageDecoding",
  transcribing: "stageTranscribing",
  understanding: "stageUnderstanding",
  saving: "stageSaving",
};

export function NewOrderSheet({ shop, onClose }: { shop: Shop; onClose: () => void }) {
  const t = useTranslations();
  const router = useRouter();
  const fileRef = useRef<HTMLInputElement>(null);
  const { progress, run, reset } = useLongTranscribe(shop);
  const recorder = useRecorder({ maxSec: 120, onAutoStop: (r) => void go(r.samples) });
  const busy = !["idle", "error", "done"].includes(progress.stage);

  const go = async (input: Blob | Float32Array) => {
    const id = await run(input);
    if (id) {
      onClose();
      router.push(`/orders/${id}`);
    }
  };

  const sample = async (file: string) => {
    try {
      const res = await fetch(file);
      if (!res.ok) throw new Error();
      await go(await res.blob());
    } catch {
      reset();
    }
  };

  return (
    <BottomSheet label={t("newOrder")} onClose={onClose} dismissible={!busy}>
      <div className="mb-2 flex items-center justify-between">
        <h2 className="text-xl font-semibold">{t("newOrder")}</h2>
        {!busy && (
          <button type="button" onClick={onClose} aria-label={t("close")} className="rounded-full p-2 text-muted">
            <X className="h-6 w-6" />
          </button>
        )}
      </div>
      <p className="mb-4 text-sm text-muted">{t("orderSheetHint")}</p>

      {busy || progress.stage === "error" ? (
        <div className="flex flex-col items-center py-4 text-center">
          <DostOrb state={progress.stage === "error" ? "sad" : "thinking"} size={110} />
          <p className="mt-3 text-lg font-semibold" aria-live="polite">
            {progress.stage === "error" && progress.errorKey ? t(progress.errorKey) : STAGE_KEY[progress.stage] ? t(STAGE_KEY[progress.stage]) : ""}
            {progress.stage === "transcribing" && progress.chunks > 1 && ` (${progress.chunk}/${progress.chunks})`}
          </p>
          {progress.language && <span className="mt-1 rounded-full bg-saffron-soft px-3 py-0.5 text-sm font-semibold text-saffron">{LANGUAGES[progress.language].nativeName}</span>}
          {progress.transcript && <p className="mt-3 max-h-32 overflow-y-auto rounded-2xl bg-card px-4 py-3 text-left text-sm">“{progress.transcript}”</p>}
          {progress.stage === "error" && (
            <motion.button type="button" {...press} onClick={reset} className="mt-4 rounded-full bg-brand px-5 py-3 font-semibold text-brand-ink shadow-card">
              {t("tryAgain")}
            </motion.button>
          )}
        </div>
      ) : recorder.status === "recording" ? (
        <div className="flex flex-col items-center py-4">
          <DostOrb state="listening" level={recorder.level} size={120} />
          <p className="tabular mt-2 font-semibold text-muted">{Math.floor(recorder.elapsed)}s / 120s</p>
          <motion.button
            type="button"
            {...press}
            onClick={async () => {
              const r = await recorder.stop();
              if (r) await go(r.samples);
            }}
            className="mt-3 flex min-h-12 items-center gap-2 rounded-full bg-chili px-6 font-semibold text-white shadow-card"
          >
            <Square className="h-4 w-4 fill-current" /> {t("done")}
          </motion.button>
        </div>
      ) : (
        <>
          <div className="grid grid-cols-2 gap-3">
            <motion.button
              type="button"
              {...press}
              onClick={() => fileRef.current?.click()}
              className="flex min-h-28 flex-col items-center justify-center gap-2 rounded-card border border-line bg-card font-semibold shadow-card"
            >
              <FileAudio className="h-8 w-8 text-saffron" /> {t("audioFile")}
            </motion.button>
            <motion.button
              type="button"
              {...press}
              onClick={() => void recorder.start()}
              className="flex min-h-28 flex-col items-center justify-center gap-2 rounded-card border border-line bg-card font-semibold shadow-card"
            >
              <Mic className="h-8 w-8 text-brand-strong" /> {t("record")}
            </motion.button>
          </div>
          <input
            ref={fileRef}
            type="file"
            accept="audio/*,.opus,.ogg,.m4a,.mp3,.wav,.aac"
            className="hidden"
            onChange={(e) => {
              const f = e.target.files?.[0];
              if (f) void go(f);
              e.target.value = "";
            }}
          />
          <h3 className="mb-2 mt-5 text-sm font-semibold uppercase tracking-wide text-muted">{t("trySample")}</h3>
          <div className="grid gap-2">
            {SAMPLE_ORDERS.map((s) => (
              <motion.button
                key={s.file}
                type="button"
                {...press}
                onClick={() => void sample(s.file)}
                className="flex min-h-12 items-center gap-3 rounded-2xl border border-line bg-card px-4 text-left font-semibold"
              >
                <span aria-hidden>{s.flag}</span> {[s.lang ? LANGUAGES[s.lang].nativeName : "Hinglish", s.note ? t(s.note) : null].filter(Boolean).join(" · ")}
              </motion.button>
            ))}
          </div>
        </>
      )}
    </BottomSheet>
  );
}
